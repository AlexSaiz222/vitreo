// Vitreo 3D pipeline, step 3 of 3 (docs/04): scaffold a React component for a
// model with gltfjsx, as a starting point for the real one in
// src/scene/models/.
//
//   pnpm models:jsx plant_basil_01
//
// Writes assets/generated/<name>.tsx (not part of the app, not linted). It
// shows the node names, transforms (meshopt quantisation moves scale into the
// nodes), materials and shape keys of the optimised model. On Windows,
// gltfjsx mangles --root and repeats its header; both are fixed here.
//
// Not for vitreo.glb: gltfjsx 6.5 bundles an old three.js whose loader fails
// on a mesh with shape keys shared by several nodes (foliage_seedling). The
// app does not use the scaffold; its components look nodes up by name.
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const name = process.argv[2];
if (!name) {
  console.error('Usage: pnpm models:jsx <model name>   e.g. plant_basil_01');
  process.exit(1);
}

const web = path.resolve(import.meta.dirname, '..');
const modelDir = path.join(web, 'public/models');
const output = path.resolve(web, '../../assets/generated', `${name}.tsx`);
mkdirSync(path.dirname(output), { recursive: true });

// Run gltfjsx's CLI with this Node (no shell, so arguments are passed as is).
const cli = path.join(
  path.dirname(createRequire(import.meta.url).resolve('gltfjsx/package.json')),
  'cli.js',
);
const result = spawnSync(
  process.execPath,
  [cli, `${name}.glb`, '--types', '--keepnames', '--shadows', '--output', output],
  { cwd: modelDir, stdio: 'inherit' },
);
if (result.status !== 0) process.exit(result.status ?? 1);

const header = /\/\*\nAuto-generated by: https:\/\/github\.com\/pmndrs\/gltfjsx\n[^*]*\*\/\n/g;
let source = readFileSync(output, 'utf8');
const first = header.exec(source)?.[0] ?? '';
source = first + source.replace(header, '');
// Whatever path gltfjsx wrote, the app serves models from /models/.
source = source.replace(/useGLTF(\.preload)?\('[^']*'\)/g, `useGLTF$1('/models/${name}.glb')`);
writeFileSync(output, source);
console.info(`Scaffold written to assets/generated/${name}.tsx`);
